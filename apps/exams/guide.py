SUPPORT_PLACEHOLDER = "{support}"


def default_guide_html(school=None):
    """متن راهنما به‌صورت HTML امن. اگر مدرسه متن اختصاصی یا شماره‌ی پشتیبانی داشته باشد، همان به‌کار می‌رود."""
    support = ""
    lines = DEFAULT_GUIDE_LINES
    if school is not None:
        from apps.accounts.models import SchoolProfile
        prof = SchoolProfile.objects.filter(school=school).first()
        if prof:
            support = (prof.exam_support or "").strip() or ((prof.phone or "").strip() and f"تلفن مدرسه: {prof.phone.strip()}") or ""
            if (prof.exam_guide or "").strip():
                return "".join(f"<p>{html.escape(x)}</p>" for x in prof.exam_guide.strip().split("\n") if x.strip())
    contact = support or "پشتیبانی مدرسه (شماره یا آیدی را از مدیر مدرسه بپرسید)"
    out, items = [], []
    for kind, text in lines:
        text = text.replace(SUPPORT_PLACEHOLDER, contact)
        if kind == "li":
            items.append(f"<li>{html.escape(text)}</li>")
            continue
        if items:
            out.append("<ul>" + "".join(items) + "</ul>")
            items = []
        tag = "h3" if kind == "h" else "p"
        out.append(f"<{tag}>{html.escape(text)}</{tag}>")
    if items:
        out.append("<ul>" + "".join(items) + "</ul>")
    return "".join(out)
